"""
Generator for the package's dark mode CSS.

Writes two files to ``static/adminlte2_pdq/css/dark-mode/``:

* ``dark-skins.css``: AdminLTE 2.3.11's six skins, renamed from ``skin-{color}`` to
  ``skin-{color}-dark``. They draw the header and the dark sidebar.
* ``dark-mode.css``: page content in dark mode. It is ``css_source/dark_mode.css`` with
  ``.pdq-dark`` replaced by the six dark skin classes, plus dark values for the package's
  ``--pdq-*`` color variables.

Both files only apply under a ``skin-{color}-dark`` body class, so they are always loaded.
Set ``ADMINLTE2_SKIN_CLASS = "skin-blue-dark"`` (or another dark skin) to use dark mode.

Run from the repository root after changing this file or css_source/dark_mode.css:

    python -m adminlte2_pdq.dark_css

The generated files are committed. A test fails when they are out of date.
"""

# System Imports.
import re
import sys
from pathlib import Path

# Internal Imports.
from adminlte2_pdq import color_css


PACKAGE_DIR = Path(__file__).resolve().parent
ADMINLTE_SKINS_DIR = PACKAGE_DIR / "static" / "third-party" / "admin-lte" / "2.3.11" / "css" / "skins"
SOURCE_FILE = PACKAGE_DIR / "css_source" / "dark_mode.css"
OUTPUT_DIR = PACKAGE_DIR / "static" / "adminlte2_pdq" / "css" / "dark-mode"

SKINS = ("blue", "black", "purple", "yellow", "red", "green")
DARK_SKIN_CLASSES = tuple(f"skin-{skin}-dark" for skin in SKINS)
DARK_SELECTOR = ":is(" + ", ".join(f".{skin_class}" for skin_class in DARK_SKIN_CLASSES) + ")"

# Dark tints that dark mode's palette (css_source/dark_mode.css) defines by hand. Other colors use dark_tint().
TINT_VARIABLES = {
    "success": "--pdq-dark-success",
    "info": "--pdq-dark-info",
    "warning": "--pdq-dark-warning",
    "danger": "--pdq-dark-danger",
    "orange": "--pdq-dark-orange",
    "purple": "--pdq-dark-purple",
}

# Colors that are light by design take dark mode's grays, with white text.
DARK_GRAY_COLORS = {
    "default": {
        "text": "var(--pdq-dark-text)",
        "base": "var(--pdq-dark-border)",
        "active": "var(--pdq-dark-border-strong)",
        "border": "var(--pdq-dark-border-strong)",
        "hover": "var(--pdq-dark-border-strong)",
    },
    "gray": {
        "text": "var(--pdq-dark-text)",
        "base": "var(--pdq-dark-default)",
        "active": "var(--pdq-dark-border)",
        "border": "var(--pdq-dark-border)",
        "hover": "var(--pdq-dark-border)",
    },
}


def dark_tint(value, hover=False):
    """A dark tint of a color, for table rows and code: its hue, at most 50% saturation, 22% lightness."""
    return color_css.tint(value, 0.50, 0.27 if hover else 0.22)


def render_skins():
    """Render AdminLTE's skins renamed to their dark classes."""
    parts = [
        "/**",
        " * AdminLTE PDQ dark skins.",
        " *",
        " * GENERATED by adminlte2_pdq/dark_css.py. Do not edit by hand.",
        " *",
        " * AdminLTE 2.3.11's skin-{color}.css files (MIT License, Copyright (c) 2014-2016 Abdullah Almsaeed),",
        " * with `.skin-{color}` renamed to `.skin-{color}-dark`. They draw the header and the dark sidebar;",
        " * dark-mode.css draws the page content.",
        " */",
    ]
    for skin in SKINS:
        css = (ADMINLTE_SKINS_DIR / f"skin-{skin}.css").read_text(encoding="utf-8")
        css = re.sub(rf"\.skin-{skin}(?![\w-])", f".skin-{skin}-dark", css)
        parts += ["", ""] + [css.strip()]
    return "\n".join(parts) + "\n"


def render_variable_overrides():
    """Render dark values for the package's --pdq-* color variables.

    Every name is set, aliases included: an alias's variable is resolved on :root, so it would
    otherwise keep the light value.
    """
    lines = [f"{DARK_SELECTOR} {{", "    --pdq-table-body-text: var(--pdq-dark-text);"]
    for name in color_css.NAMES:
        canonical = color_css.ALIASES.get(name, name)
        color = color_css.COLORS_BY_NAME[canonical]
        values = dict(DARK_GRAY_COLORS.get(canonical, {}))
        if canonical in TINT_VARIABLES:
            values["light-accent"] = f"var({TINT_VARIABLES[canonical]})"
            values["table-hover"] = f"var({TINT_VARIABLES[canonical]}-hover)"
        elif canonical in DARK_GRAY_COLORS:
            values["light-accent"] = "var(--pdq-dark-raised)"
            values["table-hover"] = "var(--pdq-dark-raised-hover)"
        else:
            values["light-accent"] = dark_tint(color.base)
            values["table-hover"] = dark_tint(color.base, hover=True)
        values["light-accent-text"] = "var(--pdq-dark-text-soft)"

        lines.append(f"    /* {name} */")
        lines += [f"    --pdq-{name}-{part}: {value};" for part, value in values.items()]
    lines.append("}")
    return "\n".join(lines)


def render_dark_mode():
    """Render the dark mode content CSS."""
    source = SOURCE_FILE.read_text(encoding="utf-8")
    # Drop the source file's own header comment.
    source = re.sub(r"\A/\*\*.*?\*/\s*", "", source, flags=re.S)
    source = source.replace(".pdq-dark", DARK_SELECTOR)

    parts = [
        "/**",
        " * AdminLTE PDQ dark mode.",
        " *",
        " * GENERATED by adminlte2_pdq/dark_css.py from adminlte2_pdq/css_source/dark_mode.css.",
        " * Do not edit by hand.",
        " *",
        " * Every rule applies only under a skin-{color}-dark body class. Set ADMINLTE2_SKIN_CLASS to a",
        " * dark skin to use it, or swap the body's skin class to switch at runtime.",
        " */",
        "",
        "",
        source.strip(),
        "",
        "",
        "/* region Package color variables */",
        render_variable_overrides(),
        "/* endregion Package color variables */",
    ]
    return "\n".join(parts) + "\n"


OUTPUTS = {
    "dark-skins.css": render_skins,
    "dark-mode.css": render_dark_mode,
}


def main():
    """Write the generated dark mode CSS files."""
    OUTPUT_DIR.mkdir(parents=True, exist_ok=True)
    for file_name, render in OUTPUTS.items():
        (OUTPUT_DIR / file_name).write_text(render(), encoding="utf-8")
        print(f"Wrote {OUTPUT_DIR / file_name}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
